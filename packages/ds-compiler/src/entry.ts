import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Diagnostics } from './errors.js';
import { COMPONENTS_DIR, ENTRY_FILE, TOKENS_DIR } from './paths.js';
import {
  codeUnitCompare,
  listComponentDirs,
  listTokenFiles,
} from './sources.js';

export const ENTRY_HEADER = `/* Generated by bwp-ds build. Do not edit by hand.
   Order: token files alphabetical by category, then components alphabetical. */`;

export interface EntrySources {
  /** Token category file names without the .css extension, code-unit sorted. */
  tokens: string[];
  /** Component directory names that contain <name>.css, code-unit sorted. */
  components: string[];
}

/** Whether `path` names a regular file, following symlinks. False for anything missing, broken, or not a file. */
function isRegularFile(path: string): boolean {
  try {
    return statSync(path).isFile();
  } catch {
    return false;
  }
}

/** A file's contents; `null` when it does not exist; an unreadable-cause sentinel for anything else short of a real read error. */
type ReadOutcome = string | null | { unreadable: string };

function readIfPresent(path: string): ReadOutcome {
  try {
    return readFileSync(path, 'utf8');
  } catch (err) {
    const code = (err as NodeJS.ErrnoException).code;
    if (code === 'ENOENT') {
      return null;
    }
    if (code === 'EISDIR' || code === 'ENOTDIR' || code === 'EACCES') {
      return { unreadable: code };
    }
    throw err;
  }
}

/**
 * Every `<name>.css` under src/tokens and every `<name>/` under src/components
 * that contains `<name>.css`. Built on the same directory listings buildIR
 * uses (`./sources.js`), so the entry file and the IR cannot drift on what
 * counts as a source. Validation of names and contents is buildIR's job;
 * this only decides what the entry file imports.
 */
export function discoverEntrySources(rootDir: string): EntrySources {
  // listTokenFiles/listComponentDirs already return code-unit sorted names,
  // and filtering preserves that order, so no re-sort is needed here.
  const tokens = listTokenFiles(rootDir)
    .filter((name) => name.endsWith('.css'))
    .map((name) => name.slice(0, -'.css'.length));
  const components = listComponentDirs(rootDir).filter((name) =>
    isRegularFile(join(rootDir, COMPONENTS_DIR, name, `${name}.css`)),
  );
  return { tokens, components };
}

export function renderEntryCss(sources: EntrySources): string {
  const tokens = [...sources.tokens].sort(codeUnitCompare);
  const components = [...sources.components].sort(codeUnitCompare);
  const lines = [ENTRY_HEADER];
  if (tokens.length > 0) {
    lines.push('', ...tokens.map((t) => `@import './tokens/${t}.css';`));
  }
  if (components.length > 0) {
    lines.push(
      '',
      ...components.map((c) => `@import './components/${c}/${c}.css';`),
    );
  }
  return `${lines.join('\n')}\n`;
}

export function expectedEntryCss(rootDir: string): string {
  return renderEntryCss(discoverEntrySources(rootDir));
}

/** Adds DS-E070 when src/index.css is missing, unreadable, or differs from what build would write. */
export function checkEntryCss(rootDir: string, diag: Diagnostics): void {
  const actual = readIfPresent(join(rootDir, ENTRY_FILE));
  const expected = expectedEntryCss(rootDir);
  if (actual === expected) {
    return;
  }
  let message: string;
  if (actual === null) {
    message = `${ENTRY_FILE} is missing`;
  } else if (typeof actual === 'object') {
    message = `${ENTRY_FILE} is not readable (${actual.unreadable})`;
  } else {
    message = `${ENTRY_FILE} does not match the files under ${TOKENS_DIR} and ${COMPONENTS_DIR}`;
  }
  diag.add('DS-E070', message, { file: ENTRY_FILE, line: 1, column: 1 });
}

/** Writes src/index.css when its content would change. */
export function writeEntryCss(rootDir: string): {
  path: string;
  changed: boolean;
} {
  const path = join(rootDir, ENTRY_FILE);
  const expected = expectedEntryCss(rootDir);
  if (readIfPresent(path) === expected) {
    return { path, changed: false };
  }
  try {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, expected);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    throw new Error(`cannot write ${ENTRY_FILE}: ${message}`);
  }
  return { path, changed: true };
}
