// The icon stage: spec/icons.json from docs/solar-icons, then React, raw SVG and Flutter.
import { join } from 'node:path';
import { buildIconSpec, loadIconCatalog } from '../normalize/icons.mjs';
import { emitReactIcons } from '../emit/react-icons.mjs';
import { emitSvgFiles } from '../emit/svg-files.mjs';
import { emitReactLogos } from '../emit/react-logos.mjs';
import { emitFlutterIcons } from '../emit/flutter-icons.mjs';
import { specDir } from '../util/paths.mjs';
import { writeGenerated } from '../util/write.mjs';

export const name = 'icons';

export function build() {
  const catalog = loadIconCatalog();
  const { spec, deviations } = buildIconSpec(catalog);
  return { catalog, spec, deviations };
}

export function emit({ catalog, spec, deviations }) {
  writeGenerated(
    join(specDir, 'icons.json'),
    JSON.stringify(
      {
        $description:
          'SOLAR icons and logos as drawing data. Generated by @bwp-web/codegen from docs/solar-icons/catalog.json and the SVG files beside it. An icon path carries only {d, fillRule} and inherits its colour (color.icon.* through currentColor); a logo path always carries its own brand fill. Do not edit.',
        $extensions: {
          'com.biamp.solar': {
            source: {
              catalog: 'docs/solar-icons/catalog.json',
              fileVersion: catalog.fileVersion,
              sourceFetchedOn: catalog.sourceFetchedOn,
              iconFill: catalog.iconFill,
              count: catalog.count,
            },
          },
        },
        ...spec,
      },
      null,
      2,
    ) + '\n',
  );

  const counts = {
    react: emitReactIcons(spec),
    svg: emitSvgFiles(spec),
    logos: emitReactLogos(spec),
    flutter: emitFlutterIcons(spec),
  };
  return { counts, deviations };
}
