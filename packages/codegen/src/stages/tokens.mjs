// The token stage: spec/tokens.json from docs/, then CSS, MUI, Tailwind and Flutter.
import { join } from 'node:path';
import { buildTokenSpec, loadContract } from '../normalize/tokens.mjs';
import { emitCss } from '../emit/css.mjs';
import { emitMui } from '../emit/mui.mjs';
import { emitTailwind } from '../emit/tailwind.mjs';
import { emitFlutter } from '../emit/flutter.mjs';
import { specDir } from '../util/paths.mjs';
import { writeGenerated } from '../util/write.mjs';

export const name = 'tokens';

export function build() {
  const contract = loadContract();
  const { spec, deviations } = buildTokenSpec(contract);
  return { contract, spec, deviations };
}

export function emit({ contract, spec, deviations }) {
  writeGenerated(
    join(specDir, 'tokens.json'),
    JSON.stringify(
      {
        $description:
          'SOLAR design tokens in DTCG format. Generated by @bwp-web/codegen from docs/solar/tokens/css-contract.json and docs/solar-web/tokens/layout-variables.json. Modes live under $extensions["com.biamp.solar"].modes. Do not edit.',
        $extensions: {
          'com.biamp.solar': {
            source: contract.generatedFrom,
            layout: contract.layoutSource,
          },
        },
        ...spec,
      },
      null,
      2,
    ) + '\n',
  );

  const mui = emitMui(spec);
  const counts = {
    css: emitCss(spec),
    mui: mui.count,
    tailwind: emitTailwind(spec),
    flutter: emitFlutter(spec),
  };
  return { counts, deviations: [...deviations, ...mui.deviations] };
}
