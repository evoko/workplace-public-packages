import { join } from 'node:path';
import { specDir } from '../util/paths.mjs';
import { writeGenerated } from '../util/write.mjs';
import { byCodeUnit } from '../util/sort.mjs';

const cell = (value) => String(value).replaceAll('|', '\\|');

// A finding the overlay has ruled on stays in the report -- a decision to differ from Figma must
// stay visible -- with the ruling beside what is still asked of SOLAR.
// A shared default (spec/overlay/defaults.yaml) is named, so its rows read as one decision.
const action = (d) =>
  d.decision
    ? `**Decided (${d.decision.rule}${d.decision.default ? `, shared default ${d.decision.default}` : ''}):** ${d.decision.reason} ${d.raise ?? ''}`.trim()
    : (d.raise ?? 'no action');

/**
 * Renders the governance report as markdown. Kept separate from the write so it can be
 * asserted on without touching spec/.
 */
export function renderDeviations(deviations, fileVersion) {
  // Dedupe by token: today every rule fires at most once per token, but a future rule that
  // fires twice would otherwise silently double a row.
  const unique = [
    ...new Map(deviations.map((d) => [d.token, d])).values(),
  ].sort((a, b) => byCodeUnit(a.token, b.token));
  const rows = unique
    .map(
      (d) =>
        `| \`${d.token}\` | ${cell(d.figmaValue)} | ${cell(d.reason)} | ${cell(action(d))} |`,
    )
    .join('\n');
  return (
    `# SOLAR code deviations from Figma\n\n` +
    `Generated by \`npm run solar:codegen\` from \`spec/tokens.json\`, \`spec/icons.json\` and ` +
    `\`spec/components/\`. Foundations Figma file version \`${fileVersion}\`; the \`icon.*\` and \`logo.*\` ` +
    `rows come from the SOLAR Icons file and the \`component.*\` rows from SOLAR Web, whose versions are ` +
    `recorded in their spec files.\n\n` +
    `Each row is a place where the generated code deliberately differs from what the Figma data says.\n` +
    `The mirror in \`docs/\` is never edited to accommodate these; take them to SOLAR governance.\n\n` +
    (unique.length
      ? `| Token | Figma value | Why we differ | Action |\n| --- | --- | --- | --- |\n${rows}\n`
      : `No deviations.\n`)
  );
}

export function writeDeviationsReport(deviations, fileVersion) {
  return writeGenerated(
    join(specDir, 'deviations.md'),
    renderDeviations(deviations, fileVersion),
  );
}
