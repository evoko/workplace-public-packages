import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import * as stage from '../src/stages/components.mjs';
import { DESCRIPTORS, fileOfDescriptor } from '../src/components/index.mjs';
import {
  componentsSrc,
  flutterComponents,
  flutterFileOf,
  headerOf,
  isGenerated,
  renderShells,
  shellFileOf,
  staleShells,
  storiesDir,
  storyFileOf,
  storyTemplate,
} from '../src/shells/index.mjs';

const { built } = stage.build();
const button = built.find((b) => b.spec.component === 'Button').spec;
const shell = readFileSync(join(componentsSrc, 'Button.tsx'), 'utf8');
const widget = readFileSync(
  join(flutterComponents, 'solar_button.dart'),
  'utf8',
);
const at = (dir) => ({ src: dir, stories: dir, flutter: dir });

describe('renderShells', () => {
  it('renders each component’s story under the header naming its descriptor, and no shell', () => {
    const out = renderShells([button], {
      ...at('/x'),
      exists: () => true,
      read: () => '/** SOLAR Button. */\n',
    });
    const header =
      '// Generated by @bwp-web/codegen from packages/codegen/src/components/button.mjs. Do not edit.';
    expect(headerOf('Button')).toBe(header);
    expect(out).toEqual([
      {
        path: '/x/Button.stories.tsx',
        text: `${header}\n${storyTemplate('Button')}`,
      },
    ]);
    expect(isGenerated(out[0].text)).toBe(true);
    expect(fileOfDescriptor('Icon Button')).toBe('icon-button.mjs');
  });

  it('refuses a component whose shell is missing, or still under the generated header', () => {
    const base = { ...at('/x'), exists: () => true, read: () => '// mine\n' };
    expect(() =>
      renderShells([button], { ...base, exists: () => false }),
    ).toThrow(/Button: its shell \/x\/Button.tsx does not exist/);
    expect(() =>
      renderShells([button], {
        ...base,
        read: () => `${headerOf('Button')}\n`,
      }),
    ).toThrow(
      /starts with the generated header, but a shell is written by hand/,
    );
  });
});

describe('staleShells', () => {
  it('finds a generated shell this run did not write, and never a hand-written file', () => {
    const files = {
      '/x/Button.tsx': `${headerOf('Button')}\n`,
      '/x/Gone.tsx':
        '// Generated by @bwp-web/codegen from packages/codegen/src/components/gone.mjs. Do not edit.\n',
      '/x/Owned.tsx': '/** SOLAR Owned. */\n',
      '/x/index.ts':
        '// Generated by @bwp-web/codegen from packages/codegen/src/components/. Do not edit.\n',
    };
    const stale = staleShells((p) => p === '/x/Button.tsx', {
      dirs: ['/x'],
      list: () => Object.keys(files).map((p) => p.slice(3)),
      read: (p) => files[p],
    });
    expect(stale).toEqual(['/x/Gone.tsx']);
  });
});

describe('the Button shell', () => {
  it('takes its look from the recipe and holds no design value itself', () => {
    expect(shell).toContain("from '@bwp-web/styles/mui'");
    expect(shell).toContain('solarButtonStyle(');
    // The code, not the comments, which explain where the values come from.
    const code = shell
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .replace(/\/\/.*$/gm, '');
    expect(code).not.toMatch(/#[0-9a-f]{3,8}\b/i);
    expect(code).not.toMatch(/\d+px|var\(--solar/);
  });

  it('reads its props through the app’s MUI theme', () => {
    expect(shell).toContain("useSolarProps(inProps, 'SolarButton')");
  });

  it('gives the widget the IR’s props and slots, and no design value', () => {
    // Every IR prop a parameter but disabled, which a null onPressed says, as for Flutter's own
    // buttons.
    for (const prop of Object.keys(button.api).filter((p) => p !== 'disabled'))
      expect(widget).toMatch(new RegExp(`this\\.${prop} = `));
    expect(widget).not.toMatch(/this\.disabled = /);
    expect(widget).toContain('bool get disabled => onPressed == null;');
    for (const slot of ['iconLeading', 'iconTrailing', 'counter'])
      expect(widget).toContain(`this.${slot},`);
    // The recipe, under the app's SolarButtonThemeData.
    expect(widget).toMatch(
      /style: SolarButtonThemeData\.styled\(\s*context,\s*SolarButtonRecipe\.style\(t, p\),?\s*\)/,
    );
    const code = widget.replace(/\/\/.*$/gm, '');
    expect(code).not.toMatch(
      /Color\(0x|Colors\.(?!transparent)|EdgeInsets|fontSize|(width|height|size):\s*\d/,
    );
  });
});

describe('the stories', () => {
  it('write the export on one line where it fits 80 columns, and wrap it as Prettier does', () => {
    expect(storyTemplate('Button')).toContain(
      "export default { title: 'SOLAR/Button', ...meta('Button') } satisfies Meta;",
    );
    expect(storyTemplate('Segmented Control Item')).toContain(
      "export default {\n  title: 'SOLAR/Segmented Control Item',\n  ...meta('Segmented Control Item'),\n} satisfies Meta;",
    );
    expect(storyFileOf('Icon Button')).toBe('IconButton.stories.tsx');
  });
});

// Every component's shells: files of their own, written by hand, and its story, generated.
describe('the shells', () => {
  for (const d of DESCRIPTORS.filter((x) => !x.checkedAs)) {
    it(`${d.name}: written by hand, without the header; its story generated`, () => {
      for (const file of [
        join(componentsSrc, shellFileOf(d.name)),
        join(flutterComponents, flutterFileOf(d.name)),
      ])
        expect(isGenerated(readFileSync(file, 'utf8')), file).toBe(false);
      const story = readFileSync(join(storiesDir, storyFileOf(d.name)), 'utf8');
      expect(story.split('\n')[0]).toBe(headerOf(d.name));
      expect(story).toContain(`title: 'SOLAR/${d.name}'`);
    });
  }
});
